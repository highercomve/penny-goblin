"""Ephemeral bank browser. Only an explicitly reviewed export exits."""
import base64
import csv
import json
import os
from pathlib import Path
import signal
import sys
import tempfile
from urllib.parse import urlsplit

MAX_PDF = 32 * 1024 * 1024
DOWNLOADS = {
    "bci": ("BCI", "https://www.bci.cl/corporativo/banco-en-linea/personas", "bci.cl", "PDF", MAX_PDF),
    "boa": ("Bank of America", "https://secure.bankofamerica.com/login/sign-in/signOnV2Screen.go", "bankofamerica.com", "CSV", 8 * 1024 * 1024),
}


def bank_url(url, domain="bci.cl"):
    try:
        p = urlsplit(url)
        return (p.scheme == "https" and not p.username and not p.password
                and p.port in (None, 443)
                and (p.hostname == domain or (p.hostname or "").endswith("." + domain)))
    except ValueError:
        return False


def run(fixture=None, bank="bci"):
    name, login, domain, file_type, limit = DOWNLOADS[bank]
    error_prefix = "Bci" if bank == "bci" else "Boa"
    import gi
    gi.require_version("Gtk", "4.0")
    gi.require_version("WebKit", "6.0")
    from gi.repository import Gtk, GLib, WebKit
    from bank_chrome import BankChrome

    Gtk.init()
    loop = GLib.MainLoop()
    session = WebKit.NetworkSession.new_ephemeral()
    view = WebKit.WebView(network_session=session)
    settings = view.get_settings()
    settings.set_hardware_acceleration_policy(WebKit.HardwareAccelerationPolicy.NEVER)
    settings.set_enable_webrtc(False)
    settings.set_enable_media_stream(False)
    # Bank exports can open a popup after an asynchronous request. Every
    # popup still passes our origin policy and the four-page limit below.
    settings.set_javascript_can_open_windows_automatically(True)
    window = Gtk.Window(title=f"Penny Goblin — {name}")
    window.set_default_size(1100, 800)
    chrome = BankChrome(window, view, bank=name, download=True, file_type=file_type)
    pages = [view]
    output = None
    captured = None
    active = None
    sequence = 0
    storage = tempfile.TemporaryDirectory(prefix="penny-bci-")

    def allowed(url):
        if url.startswith("blob:"):
            url = url[5:]
        if fixture:
            p, expected = urlsplit(url), urlsplit(fixture)
            return p.scheme == "http" and p.netloc == expected.netloc and not p.username and not p.password
        return bank_url(url, domain)

    def finish(value):
        nonlocal output
        if output is None:
            output = value
            loop.quit()

    def consume(data):
        nonlocal captured
        try:
            if len(data) > limit:
                raise ValueError()
            if bank == "bci":
                if not data.startswith(b"%PDF-"):
                    raise ValueError()
                captured = {"pdf_base64": base64.b64encode(data).decode("ascii")}
            else:
                from boa_parser import parse
                captured = {"rows": parse(data)}
            chrome.update(3, f"Movements {file_type} ready", f"Check the selected {name} account. Penny Goblin will offer only this month’s charges for review.", ready=True)
            if fixture:
                chrome.primary.emit("clicked")
        except (ValueError, csv.Error):
            captured = None
            chrome.update(2, "Couldn’t read this export", f"Download the account’s movements as a {file_type} from {name}. Other layouts are not supported.", error=True)

    def data_export(url, page):
        nonlocal captured
        # FileSaver/jsPDF use data URLs on WebKit. They have no hostname:
        # accept only PDFs generated by a currently trusted bank page, never
        # by a blank popup or an external origin, and do not navigate to them.
        if active is not None or bank != "bci" or not url.startswith("data:") or page is None or not allowed(page.get_uri() or ""):
            return False
        captured = None
        try:
            header, encoded = url.split(",", 1)
            # FileSaver's Safari/WebKit path changes the MIME to attachment/file.
            mime = header.split(";", 1)[0].lower()
            if len(header) > 1024 or mime not in ("data:application/pdf", "data:application/octet-stream", "data:attachment/file") or not header.lower().endswith(";base64") or len(encoded) > ((limit + 2) // 3) * 4:
                raise ValueError()
            consume(base64.b64decode(encoded, validate=True))
        except ValueError:
            chrome.update(2, "Couldn’t read this PDF", "Download a valid movements PDF from the bank page.", error=True)
        return True

    def policy(_view, decision, kind):
        if kind == WebKit.PolicyDecisionType.RESPONSE:
            response = decision.get_response()
            if decision.is_main_frame_main_resource() and response.get_mime_type() in ("application/pdf", "text/csv", "application/csv"):
                if allowed(response.get_uri()):
                    decision.download()
                else:
                    decision.ignore()
                return True
        if kind in (WebKit.PolicyDecisionType.NAVIGATION_ACTION, WebKit.PolicyDecisionType.NEW_WINDOW_ACTION):
            action = decision.get_navigation_action()
            url = action.get_request().get_uri()
            if data_export(url, _view):
                decision.ignore()
                return True
            if url == "about:blank" and kind != WebKit.PolicyDecisionType.NEW_WINDOW_ACTION:
                return False
            blank_popup = url == "about:blank" and allowed(_view.get_uri() or "")
            if not allowed(url) and not blank_popup:
                decision.ignore()
                if action.is_user_gesture():
                    chrome.update(1, "External navigation blocked", f"Use the {name} page in this window to continue.")
                return True
        return False

    def create(parent, action):
        url = action.get_request().get_uri()
        if data_export(url, parent):
            return None
        blank = url == "about:blank" and allowed(parent.get_uri() or "")
        if len(pages) >= 4 or (not allowed(url) and not blank):
            return None
        # A related WebView preserves POST bodies and the ephemeral session.
        # Replacing a popup with load_uri would silently turn a login POST
        # into a GET. Keep the pages in this single protected bank window.
        child = WebKit.WebView(related_view=parent)
        child.set_settings(settings)
        pages.append(child)
        attach(child)
        chrome.show_view(child)

        def closed(page):
            chrome.show_view(parent)
            chrome.pages.remove(page)
            pages.remove(page)

        child.connect("close", closed)
        return child

    def download_started(_session, download):
        nonlocal active, captured, sequence
        uri = download.get_request().get_uri()
        if active is None and data_export(uri, download.get_web_view()):
            download.cancel()
            return
        if uri.startswith("blob:"):
            uri = uri[5:]
        if active is not None or not allowed(uri):
            download.cancel()
            return
        active = download
        captured = None
        sequence += 1
        destination = Path(storage.name) / f"movements-{sequence}.{file_type.lower()}"
        total = 0

        def choose(_download, name):
            response = download.get_response()
            mime = response.get_mime_type()
            supported = (mime == "application/pdf" or (mime == "application/octet-stream" and name.lower().endswith(".pdf"))) if bank == "bci" else (
                mime in ("text/csv", "application/csv") or (mime in ("application/octet-stream", "application/vnd.ms-excel", "text/plain") and name.lower().endswith(".csv")))
            if not allowed(response.get_uri()) or not supported or response.get_content_length() > limit:
                download.cancel()
                return True
            download.set_destination(str(destination))
            chrome.update(2, "Downloading movements…", "Keep this window open. No payments have been saved.", busy=True)
            return True

        def received(_download, length):
            nonlocal total
            total += length
            if total > limit:
                download.cancel()

        def failed(_download, _error):
            nonlocal active
            active = None
            destination.unlink(missing_ok=True)
            chrome.update(2, "Couldn’t download movements", f"Choose a {file_type} export up to {limit // (1024 * 1024)} MB and try its download again.", error=True)

        def completed(_download):
            nonlocal active
            active = None
            try:
                with destination.open("rb") as source:
                    data = source.read(limit + 1)
                consume(data)
            except OSError:
                chrome.update(2, "Couldn’t read this export", f"Download the account’s movements as a {file_type} from {name}. Other layouts are not supported.", error=True)
            finally:
                destination.unlink(missing_ok=True)

        download.connect("decide-destination", choose)
        download.connect("received-data", received)
        download.connect("failed", failed)
        download.connect("finished", completed)

    def primary(*_):
        if captured is not None and chrome.action == "review":
            finish(captured)
        else:
            chrome.view.load_uri(fixture or login)

    def loading(_view, event):
        if _view is not chrome.view:
            return
        if active is not None or captured is not None:
            return
        if event == WebKit.LoadEvent.STARTED:
            chrome.update(1, f"Loading {name}…", "Your sign-in stays in this private bank window.", busy=True)
        elif event == WebKit.LoadEvent.FINISHED and chrome.action != "retry":
            chrome.update(2, "Download your movements", f"Sign in, open your card or account’s movements, then download its {file_type} here.")

    def failed(_view, _event, _uri, error):
        if not error.matches(WebKit.network_error_quark(), WebKit.NetworkError.CANCELLED):
            chrome.update(chrome.stage, f"Couldn’t load {name}", error.message, error=True)
        return True

    chrome.primary.connect("clicked", primary)
    chrome.back.connect("clicked", lambda *_: chrome.view.load_uri(fixture or login))

    def attach(page):
        page.connect("decide-policy", policy)
        page.connect("create", create)
        page.connect("permission-request", lambda _, request: (request.deny(), True)[1])
        page.connect("load-changed", loading)
        page.connect("notify::estimated-load-progress", lambda *_: chrome.page_progress(page))
        page.connect("notify::is-loading", lambda *_: chrome.page_progress(page))
        page.connect("load-failed", failed)
        page.connect("load-failed-with-tls-errors", lambda *_: (chrome.update(chrome.stage, "Connection couldn’t be verified", f"{name}’s certificate could not be verified. Close this window and try later.", error=True), True)[1])
        page.connect("web-process-terminated", lambda *_: finish({"error": error_prefix + "BrowserUnavailable"}))

    attach(view)
    view.connect("close", lambda *_: finish({"error": "Cancelled"}))
    session.connect("download-started", download_started)
    window.connect("close-request", lambda *_: (finish({"error": "Cancelled"}), True)[1])
    previous_signal = signal.signal(signal.SIGTERM, lambda *_: GLib.idle_add(lambda: (finish({"error": "Cancelled"}), False)[1]))
    timer = GLib.timeout_add_seconds(15 * 60, lambda: (finish({"error": error_prefix + "LoginTimedOut"}), False)[1])
    window.present()
    view.load_uri(fixture or login)
    try:
        loop.run()
    finally:
        if output is not None and output.get("error") != error_prefix + "LoginTimedOut":
            GLib.source_remove(timer)
        if active is not None:
            active.cancel()
        for page in pages:
            page.stop_loading()
        window.destroy()
        storage.cleanup()
        signal.signal(signal.SIGTERM, previous_signal)
    return output or {"error": "Cancelled"}


def main(bank):
    protocol = os.fdopen(os.dup(sys.stdout.fileno()), "w", buffering=1)
    os.dup2(sys.stderr.fileno(), sys.stdout.fileno())
    fixture = None
    if len(sys.argv) == 3 and sys.argv[1] == "--fixture-url":
        fixture = sys.argv[2]
        p = urlsplit(fixture)
        if p.scheme != "http" or p.hostname != "127.0.0.1" or p.username or p.password:
            raise SystemExit(1)
    elif len(sys.argv) != 1:
        raise SystemExit(1)
    try:
        result = run(fixture, bank)
    except Exception:
        result = {"error": "BciBrowserUnavailable" if bank == "bci" else "BoaBrowserUnavailable"}
    print(json.dumps(result, separators=(",", ":")), file=protocol, flush=True)
